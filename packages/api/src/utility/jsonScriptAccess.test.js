// Regression tests for the checks on JSON scripts (runners/start, runners/script-result,
// runners/load-reader, database-connections/eval-json-script).
//
// Each `assign` command of a JSON script calls a shell API function with props chosen by the
// client. Nothing checked them: any logged-in user could run queryReader / tableWriter on any
// connection id, call any shell function (executeQuery, runScript, deployDb, ...) and zip any
// server directory into any file.

jest.mock('../auth/authProvider', () => ({
  getAuthProviderFromReq: jest.fn(() => ({
    getCurrentPermissions: async req => req.permissions,
    checkCurrentConnectionPermission: async () => true,
    getCurrentDatabasePermissions: async req => req.databasePermissions ?? [],
    getCurrentTablePermissions: async req => req.tablePermissions ?? [],
  })),
}));
jest.mock('./directories', () => ({
  filesdir: () => '/data/files',
  uploadsdir: () => '/data/uploads',
  archivedir: () => '/data/archive',
  appdir: () => '/data/apps',
}));
jest.mock('../controllers/connections', () => ({
  testConnectionDefinitionPermission: jest.fn(async (connection, req) => {
    if (req.permissions?.includes('~admin/connections'))
      throw new Error('DBGM-00000 Permission to define connections not granted');
  }),
  // connections whose id starts with "mongo" are MongoDB, the others PostgreSQL
  getCore: jest.fn(async ({ conid }) => ({
    _id: conid,
    engine: conid.startsWith('mongo') ? 'mongo@dbgate-plugin-mongo' : 'postgres@dbgate-plugin-postgres',
  })),
}));
jest.mock('./requireEngineDriver', () =>
  jest.fn(connection => ({ databaseEngineTypes: connection.engine.startsWith('mongo') ? ['document'] : ['sql'] }))
);

const { checkJsonScriptAccess, checkShellFunctionCall } = require('./jsonScriptAccess');

const originalStorageDatabase = process.env.STORAGE_DATABASE;
beforeEach(() => {
  delete process.env.STORAGE_DATABASE;
});
afterAll(() => {
  if (originalStorageDatabase == null) delete process.env.STORAGE_DATABASE;
  else process.env.STORAGE_DATABASE = originalStorageDatabase;
});

const script = (...commands) => ({ type: 'json', commands, packageNames: [] });
const assign = (functionName, props) => ({ type: 'assign', variableName: 'var1', functionName, props });

// a login allowed to use only the connection "allowed"
const restricted = { permissions: '~connections/*,connections/allowed' };
const anyone = { permissions: undefined };

// what the import/export tab generates: table -> CSV file
const exportTableToCsv = conid =>
  script(
    assign('tableReader', {
      connection: { _id: conid, engine: 'postgres@dbgate-plugin-postgres', database: 'db' },
      pureName: 't',
    }),
    assign('writer@dbgate-plugin-csv', { fileName: 't.csv' }),
    { type: 'copyStream', sourceVar: 'var1', targetVar: 'var2', colmapVar: null, progressName: 't' },
    { type: 'endline' },
    { type: 'zipDirectory', inputDirectory: '.', outputFile: 'archive:export.zip' }
  );

describe('scripts generated by the client', () => {
  test('run for a user allowed to use the connection', async () => {
    await expect(checkJsonScriptAccess(exportTableToCsv('allowed'), restricted)).resolves.toBeUndefined();
    await expect(checkJsonScriptAccess(exportTableToCsv('any'), anyone)).resolves.toBeUndefined();
  });

  test('data deployer (dataReplicator) and import into a table run with import permission', async () => {
    const deploy = script({
      type: 'dataReplicator',
      options: { connection: { _id: 'allowed', database: 'db' }, archive: 'a', items: [] },
    });
    await expect(checkJsonScriptAccess(deploy, restricted)).resolves.toBeUndefined();
    await expect(
      checkJsonScriptAccess(deploy, { permissions: `${restricted.permissions},~dbops/import` })
    ).rejects.toThrow(/dbops\/import/);
  });

  // quick export from a table data grid generates a queryReader
  test('quick export from a data grid needs only the export permission', async () => {
    const gridExport = script(
      assign('queryReader', { connection: { _id: 'allowed', database: 'db' }, sql: 'select * from t' })
    );
    await expect(
      checkJsonScriptAccess(gridExport, { permissions: `${restricted.permissions},~dbops/query` })
    ).resolves.toBeUndefined();
  });
});

// Team Premium: write_data on the database, but the table "salaries" lowered to read only
describe('table permissions (Team Premium)', () => {
  const user = {
    permissions: '~all-tables',
    databasePermissions: [{ database_permission_role_id: -3 }],
    tablePermissions: [{ table_names_list: 'salaries', table_permission_role_id: -1, table_permission_scope_id: -1 }],
  };
  const importInto = pureName =>
    script(assign('tableWriter', { connection: { _id: 'conid1', database: 'db' }, pureName, createIfNotExists: true }));

  beforeEach(() => {
    process.env.STORAGE_DATABASE = 'postgres://storage';
  });

  test('import into a table needs create_update_delete on that table', async () => {
    await expect(checkJsonScriptAccess(importInto('orders'), user)).resolves.toBeUndefined();
    await expect(checkJsonScriptAccess(importInto('salaries'), user)).rejects.toThrow(/salaries not granted/);
  });

  test('a user with all-tables is not restricted by table permissions', async () => {
    await expect(checkJsonScriptAccess(importInto('salaries'), { ...user, permissions: '*' })).resolves.toBeUndefined();
  });
});

// dataReplicator reads <archive or folder>/<item name>.jsonl - a server directory or a path in a
// name would import any server-local JSONL file (e.g. another user's result set) into a database
describe('data deployer sources', () => {
  const deploy = options =>
    script({ type: 'dataReplicator', options: { connection: { _id: 'allowed', database: 'db' }, ...options } });

  test('an archive folder or zip with plain table names is allowed', async () => {
    for (const options of [
      { archive: 'default', items: [{ name: 'orders' }] },
      { archive: 'backup.zip', items: [{ name: 'dbo.orders' }] },
      { folder: 'archive:default', items: [{ name: 'orders' }] },
    ]) {
      await expect(checkJsonScriptAccess(deploy(options), restricted)).resolves.toBeUndefined();
    }
  });

  test.each([
    ['a server directory', { folder: '/home/dbgate/.dbgate/jsl', items: [{ name: 'x' }] }],
    ['an archive folder with a path', { folder: 'archive:../jsl', items: [{ name: 'x' }] }],
    ['an archive with a path', { archive: '../jsl', items: [{ name: 'x' }] }],
    ['an item name with a path', { archive: 'default', items: [{ name: '../../jsl/x' }] }],
    ['an item name with a backslash', { archive: 'default', items: [{ name: '..\\jsl\\x' }] }],
  ])('%s is refused', async (_label, options) => {
    await expect(checkJsonScriptAccess(deploy(options), restricted)).rejects.toThrow(/Unallowed data source/);
  });
});

// a native query of MongoDB is JavaScript evaluated in the DbGate process (driver.readQuery)
describe('native queries of document databases', () => {
  const mongoQuery = (queryType, query) =>
    script(assign('queryReader', { connection: { _id: 'mongo1', database: 'db' }, queryType, query }));

  beforeEach(() => {
    process.env.STORAGE_DATABASE = 'postgres://storage';
  });

  test('need dbops/query and the run_script role', async () => {
    const exportOnly = { permissions: '~dbops/query' };
    await expect(checkJsonScriptAccess(mongoQuery('native', 'db.t.find()'), exportOnly)).rejects.toThrow(
      /dbops\/query/
    );
    const noScriptRole = { permissions: '~all-databases', databasePermissions: [{ database_permission_role_id: -2 }] };
    await expect(checkJsonScriptAccess(mongoQuery('native', 'db.t.find()'), noScriptRole)).rejects.toThrow(
      /run_script/
    );
    const scriptRole = { ...noScriptRole, databasePermissions: [{ database_permission_role_id: -4 }] };
    await expect(checkJsonScriptAccess(mongoQuery('native', 'db.t.find()'), scriptRole)).resolves.toBeUndefined();
  });

  test('a structured query needs only the export permission', async () => {
    const exportOnly = {
      permissions: '~dbops/query,~all-databases',
      databasePermissions: [{ database_permission_role_id: -2 }],
    };
    await expect(
      checkJsonScriptAccess(mongoQuery('json', { collection: 't', condition: {} }), exportOnly)
    ).resolves.toBeUndefined();
  });
});

// archiveReader joined a zip name to the archive directory unchecked
describe('archive reader', () => {
  const read = (folderName, fileName) => script(assign('archiveReader', { folderName, fileName }));

  test('reads an archive folder or zip by its plain name', async () => {
    await expect(checkJsonScriptAccess(read('default', 'orders'), anyone)).resolves.toBeUndefined();
    await expect(checkJsonScriptAccess(read('backup.zip', 'orders'), anyone)).resolves.toBeUndefined();
  });

  test.each([
    ['../../backups/private.zip', 'orders'],
    ['..\\private.zip', 'orders'],
    ['default', '../secret'],
    [undefined, 'orders'],
  ])('refuses folder %p, file %p', async (folderName, fileName) => {
    await expect(checkJsonScriptAccess(read(folderName, fileName), anyone)).rejects.toThrow(
      /Invalid archive folder|Unallowed directories/
    );
  });
});

// the archive routes need archive/write - a script must not write into the archive without it
describe('writing into the archive', () => {
  const noArchiveWrite = { permissions: '~archive/write' };
  const csvWriter = fileName => script(assign('writer@dbgate-plugin-csv', { fileName }));

  test('archiveWriter needs archive/write', async () => {
    const toArchive = script(assign('archiveWriter', { folderName: 'default', fileName: 't' }));
    await expect(checkJsonScriptAccess(toArchive, noArchiveWrite)).rejects.toThrow(/archive\/write/);
    await expect(checkJsonScriptAccess(toArchive, anyone)).resolves.toBeUndefined();
  });

  test('a file writer with a file in the archive needs archive/write', async () => {
    await expect(checkJsonScriptAccess(csvWriter('/data/archive/t.csv'), noArchiveWrite)).rejects.toThrow(
      /archive\/write/
    );
    await expect(checkJsonScriptAccess(csvWriter('/data/uploads/t.csv'), noArchiveWrite)).resolves.toBeUndefined();
    await expect(checkJsonScriptAccess(csvWriter('t.csv'), noArchiveWrite)).resolves.toBeUndefined();
  });

  test('a zip into the archive needs archive/write', async () => {
    const zip = outputFile => script({ type: 'zipDirectory', inputDirectory: '.', outputFile });
    await expect(checkJsonScriptAccess(zip('archive:export.zip'), noArchiveWrite)).rejects.toThrow(/archive\/write/);
    await expect(checkJsonScriptAccess(zip('export.zip'), noArchiveWrite)).resolves.toBeUndefined();
  });
});

describe('scripts are refused when', () => {
  test('they use a connection the user may not use', async () => {
    await expect(checkJsonScriptAccess(exportTableToCsv('secret'), restricted)).rejects.toThrow(/not granted/);
  });

  test('the user may not export', async () => {
    await expect(
      checkJsonScriptAccess(exportTableToCsv('allowed'), { permissions: `${restricted.permissions},~dbops/export` })
    ).rejects.toThrow(/dbops\/export/);
    const queryExport = script(assign('queryReader', { connection: { _id: 'allowed', database: 'db' }, sql: 'x' }));
    await expect(
      checkJsonScriptAccess(queryExport, { permissions: `${restricted.permissions},~dbops/export` })
    ).rejects.toThrow(/dbops\/export/);
  });

  test('they call a shell function the client never generates', async () => {
    for (const functionName of ['executeQuery', 'runScript', 'deployDb', 'dropAllDbObjects', 'download', 'loadFile']) {
      await expect(checkJsonScriptAccess(script(assign(functionName, {})), anyone)).rejects.toThrow(/not allowed/);
    }
  });

  test('they use an unknown command or an unconfined zip', async () => {
    await expect(checkJsonScriptAccess(script({ type: 'importDatabase', options: {} }), anyone)).rejects.toThrow(
      /not allowed/
    );
    for (const command of [
      { type: 'zipDirectory', inputDirectory: '/etc', outputFile: 'x.zip' },
      { type: 'zipDirectory', inputDirectory: '.', outputFile: '../../x.zip' },
      { type: 'zipDirectory', inputDirectory: '.', outputFile: 'archive:../x.zip' },
    ]) {
      await expect(checkJsonScriptAccess(script(command), anyone)).rejects.toThrow(/zip/);
    }
  });

  test('they read or write files outside the data directories', async () => {
    await expect(
      checkJsonScriptAccess(script(assign('reader@dbgate-plugin-csv', { fileName: '/etc/passwd' })), anyone)
    ).rejects.toThrow(/Unallowed directories/);
  });

  test('they define a connection inline without permission to define connections', async () => {
    const inline = script(
      assign('tableReader', { connection: { engine: 'mysql@dbgate-plugin-mysql', server: '10.0.0.1' } })
    );
    await expect(checkJsonScriptAccess(inline, { permissions: '~admin/connections,~all-connections' })).rejects.toThrow(
      /define connections/
    );
  });
});

describe('runners/load-reader', () => {
  test('allows file readers and checks database readers', async () => {
    await expect(
      checkShellFunctionCall('reader@dbgate-plugin-csv', { fileName: 'x.csv' }, restricted)
    ).resolves.toBeUndefined();
    await expect(
      checkShellFunctionCall('tableReader', { connection: { _id: 'secret', database: 'db' } }, restricted)
    ).rejects.toThrow(/not granted/);
    await expect(checkShellFunctionCall('queryReader', {}, anyone)).rejects.toThrow(/not specified/);
    await expect(checkShellFunctionCall('executeQuery', {}, anyone)).rejects.toThrow(/not allowed/);
  });
});

describe('eval-json-script with a single-connection driver', () => {
  test('uses the host connection for readers without their own connection', async () => {
    const duckdbExport = script(
      assign('tableReader', { systemConnection: { $hostConnection: true }, connection: 'duckdb@dbgate-plugin-duckdb' })
    );
    await expect(
      checkJsonScriptAccess(duckdbExport, restricted, { hostConnection: { conid: 'allowed', database: 'db' } })
    ).resolves.toBeUndefined();
    await expect(
      checkJsonScriptAccess(duckdbExport, restricted, { hostConnection: { conid: 'secret', database: 'db' } })
    ).rejects.toThrow(/not granted/);
  });

  // the writer runs on the host database, whatever connection the script names
  test('a writer through the host connection is checked for the host database', async () => {
    const write = script(
      assign('tableWriter', {
        systemConnection: { $hostConnection: true },
        connection: { _id: 'allowed', database: 'db' },
        pureName: 't',
      })
    );
    await expect(
      checkJsonScriptAccess(write, restricted, { hostConnection: { conid: 'secret', database: 'db' } })
    ).rejects.toThrow(/not granted/);
  });

  test('other system connections, or the host marker without a host database, are refused', async () => {
    const withSystemConnection = systemConnection =>
      script(assign('tableReader', { systemConnection, connection: { _id: 'allowed', database: 'db' } }));
    await expect(
      checkJsonScriptAccess(withSystemConnection({ client: 'x' }), anyone, { hostConnection: { conid: 'allowed' } })
    ).rejects.toThrow(/Invalid system connection/);
    await expect(checkJsonScriptAccess(withSystemConnection({ $hostConnection: true }), anyone)).rejects.toThrow(
      /Invalid system connection/
    );
  });
});
